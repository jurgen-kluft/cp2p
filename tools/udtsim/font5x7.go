// drawTextScaled renders text at pixel position (x, y) using the 5×7 bitmap font
// scaled by the given integer factor. Each character cell is 6*scale wide (5+1 gap)
// and 7*scale tall. Characters outside the printable ASCII range are rendered as spaces.
func drawTextScaled(img *image.RGBA, x, y int, text string, scale int, c color.RGBA) {
	if scale < 1 {
		scale = 1
	}
	cx := x
	bounds := img.Bounds()
	for _, ch := range text {
		if ch < 0x20 || ch > 0x7E {
			cx += 6 * scale
			continue
		}
		glyph := font5x7[ch-0x20]
		for col := 0; col < 5; col++ {
			for row := 0; row < 7; row++ {
				if glyph[col]&(1<<uint(row)) != 0 {
					for sy := 0; sy < scale; sy++ {
						for sx := 0; sx < scale; sx++ {
							px := cx + col*scale + sx
							py := y + row*scale + sy
							if px >= bounds.Min.X && px < bounds.Max.X &&
								py >= bounds.Min.Y && py < bounds.Max.Y {
								img.SetRGBA(px, py, c)
							}
						}
					}
				}
			}
		}
		cx += 6 * scale
	}
}

// textWidth returns the pixel width of text rendered at the given scale.
func textWidth(text string, scale int) int {
	return len(text) * 6 * scale
}
